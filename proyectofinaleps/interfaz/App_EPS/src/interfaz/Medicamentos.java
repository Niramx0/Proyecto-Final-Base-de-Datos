    public void cargarMedicamentosRecetados() {
    String idUsuarioText = txtIdUsuario.getText(); // Obtener el ID del usuario desde el JTextField

    if (idUsuarioText.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, ingrese el ID del usuario.");
        return;
    }

    int idUsuario = Integer.parseInt(idUsuarioText); // Convertir a entero

    // Consulta SQL mejorada para excluir medicamentos con stock 0 o "Nada"
    String query = "SELECT m.stock, m.nombre AS medicamento, h.cantidad_med AS cantidad, (m.precio * h.cantidad_med) AS total " +
                   "FROM historial_medico h " +
                   "JOIN medicamentos m ON h.medicamentos = m.id " +
                   "WHERE h.id_usuario = ? " +
                   "AND m.stock > 0 " +          // Excluir medicamentos sin stock
                   "AND m.nombre != 'Nada' " +  // Excluir "Nada"
                   "AND h.cantidad_med > 0";    // Excluir cantidades en 0

    try (Connection conn = cx.conectar();
         PreparedStatement pst = conn.prepareStatement(query)) {

        pst.setInt(1, idUsuario); // Filtrar por ID del usuario

        try (ResultSet rs = pst.executeQuery()) {
            javax.swing.table.TableModel modelo = tablaReclamos.getModel();

            if (modelo instanceof DefaultTableModel) {
                DefaultTableModel tableModel = (DefaultTableModel) modelo;
                tableModel.setRowCount(0); // Limpiar la tabla antes de actualizar

                while (rs.next()) {
                    int stock = rs.getInt("stock");
                    String medicamento = rs.getString("medicamento");
                    int cantidad = rs.getInt("cantidad");
                    int total = rs.getInt("total"); // Precio * cantidad

                    // Agregar datos a la tabla solo si son válidos
                    tableModel.addRow(new Object[]{stock, medicamento, cantidad, total});
                }
            }
        }

    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error al cargar los medicamentos recetados.");
    }
}

  
    private int obtenerIdMedicamentoDesdeNombre(String nombreMedicamento) {
    String query = "SELECT id FROM medicamentos WHERE nombre = ?";
    int idMedicamento = -1;

    try (Connection conn = cx.conectar();
         PreparedStatement pst = conn.prepareStatement(query)) {

        pst.setString(1, nombreMedicamento);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            idMedicamento = rs.getInt("id"); // Obtener el ID del medicamento
        }

    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error al obtener el ID del medicamento.");
    }

    return idMedicamento;
}



