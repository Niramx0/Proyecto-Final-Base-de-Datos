    private void btnreclamarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnreclamarActionPerformed
 int filaSeleccionada = tablaReclamos.getSelectedRow();
    if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(this, "Por favor, seleccione un medicamento para reclamar.");
        return;
    }

    // Obtener valores de la fila seleccionada
    String nombreMedicamento = tablaReclamos.getValueAt(filaSeleccionada, 1).toString(); // Nombre del medicamento
    int cantidadReclamada = Integer.parseInt(tablaReclamos.getValueAt(filaSeleccionada, 2).toString()); // Cantidad

    // Obtener el ID del medicamento desde la base de datos
    int idMedicamento = obtenerIdMedicamentoDesdeNombre(nombreMedicamento);
    if (idMedicamento == -1) {
        JOptionPane.showMessageDialog(this, "Error al obtener el ID del medicamento.");
        return;
    }

    // Obtener el ID del usuario
    int idUsuario = Integer.parseInt(txtIdUsuario.getText());

    // Actualizar stock del medicamento en la tabla `medicamentos`
    String actualizarStockQuery = "UPDATE medicamentos SET stock = stock - ? WHERE id = ?";

    // Eliminar la receta de la tabla `historial_medico`
    String eliminarRecetaQuery = "DELETE FROM historial_medico WHERE id_usuario = ? AND medicamentos = ? AND cantidad_med = ? LIMIT 1";

    try (Connection conn = cx.conectar();
         PreparedStatement pstUpdateStock = conn.prepareStatement(actualizarStockQuery);
         PreparedStatement pstDeleteReceta = conn.prepareStatement(eliminarRecetaQuery)) {

        // Actualizar stock
        pstUpdateStock.setInt(1, cantidadReclamada);
        pstUpdateStock.setInt(2, idMedicamento);
        pstUpdateStock.executeUpdate();

        // Eliminar receta del historial
        pstDeleteReceta.setInt(1, idUsuario);
        pstDeleteReceta.setInt(2, idMedicamento);
        pstDeleteReceta.setInt(3, cantidadReclamada);
        pstDeleteReceta.executeUpdate();

        JOptionPane.showMessageDialog(this, "Medicamento reclamado con éxito.");

        // Actualizar la tabla después del reclamo
        cargarMedicamentosRecetados();

    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error al reclamar el medicamento.");
        
    }
     
    }//GEN-LAST:event_btnreclamarActionPerformed

